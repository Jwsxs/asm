	.TEXT
	.GLOBL MULTS_OF_X

MULTS_OF_X:
	PUSH %RBP
	MOVQ %RSP, %RBP
	MOV %RDI, %R9 # MAX NUMB
	XOR %R8, %R8
	XOR %R10, %R10 # MULT AMOUNT
	
LOOP:	
	INC %R8 # R8 CURRENT NUMB
	MOV %R8, %RAX # DIVIDENDO

	XOR %RDX, %RDX
	MOV $3, %RCX # DIVISOR
	DIV %RCX

	CMP $0, %RDX # SE NAO TIVER RESTO
	JNE SKIP

	INC %R10

	MOV %R8, %RAX
	CALL TO_ASCII

SKIP:
	
	CMP %R9, %R8
	JGE _fin
	JMP LOOP
	
_fin:
	MOV %R10, %RAX
	CALL TO_ASCII

	MOV $0x3C, %RAX
	XOR %RDI, %RDI
	SYSCALL

# OQ ACONTECE É O SEGUINTE:
# TENTAR "PRINTAR" UM INTEIRO DIRETAMENTE USANDO SYSCALL NAO FUNCIONA, POIS O COMPUTADOR
# ENTENDE O CODIGO QUE RECEBE DO NUMERO COMO SENDO UM OUTRO CODIGO EM TAL CUNHO CARACTERE,
# PORTANTO, O QUE PRECISA SER FEITO ANTES E SO CONVERTER O INTEIRO ATUAL PARA SEU RESPECTIVO CODIGO,
# PODENDO SE BASEAR NA TABELA ASCII
# ASSIM FEITO DA SEGUINTE MANEIRA:
# 
TO_ASCII:
	SUB $32, %RSP  # RSP AS A TEMPORARY BUFFER SINCE WE'RE ALLOCATING SPACE
				   # FOR A LOCAL VARIABLE WITH NO IMPORTANCE IN THE FUTURE
	MOV %RSP, %RCX # A WAY OF SAVING THE ADDRESS AND RETURNING THE STACK POINTER
CONV_LOOP:
	XOR %RDX, %RDX
	MOV $10, %RBX # DIVISOR
	DIV %RBX
#	NOW THERE'S A VALUE ON %RAX
#	WE JUST NEED TO ADD IT'S VALUE TO THE FIRST INTEGER ASCII CODE: 0
#	DIGITO + 0X30 = ASCII DO DIGITO
	ADD $0x30, %DL # ADD '0', %DL

	DEC %RCX
	MOV %DL, (%RCX)

	CMP $0, %RAX
	JNE CONV_LOOP

#	PRINT NUMB
	MOV $1, %RAX
	MOV $1, %RDI
	MOV %RCX, %RSI
	MOV %RSP, %RDX

	SUB %RCX, %RDX
	SYSCALL

#	PRINT '\n'
	MOV $10, %AL
	MOV %AL, (%RSP)

	MOV $1, %RAX
	MOV $1, %RDI
	MOV %RSP, %RSI
	MOV $1, %RDX
	SYSCALL
	
	ADD $32, %RSP
	RET
