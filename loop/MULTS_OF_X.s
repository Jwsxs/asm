	.TEXT
	.GLOBL MULTS_OF_X

MULTS_OF_X:
	PUSH %RBP
	MOVQ %RSP, %RBP
	MOV %RDI, %R9 # MAX NUMB
	XOR %R8, %R8
	XOR %R10, %R10 # MULT AMOUNT
	
LOOP:	
	INC %R8 # R8 CURRENT NUMB
	MOV %R8, %RAX # DIVIDENDO

	XOR %RDX, %RDX
	MOV $3, %RCX # DIVISOR
	DIV %RCX

	CMP $0, %RDX # SE NAO TIVER RESTO
	JNE SKIP

	INC %R10

	MOV %R8, %RAX
	CALL TO_ASCII

SKIP:
	
	CMP %R9, %R8
	JGE _fin
	JMP LOOP
	
_fin:
	MOV %R10, %RAX
	CALL TO_ASCII

	MOV $0x3C, %RAX
	XOR %RDI, %RDI
	SYSCALL

TO_ASCII:
	SUB $32, %RSP # RSP AS A TEMPORARY BUFFER
	MOV %RSP, %RCX
CONV_LOOP:
	XOR %RDX, %RDX
	MOV $10, %RBX # DIVISOR
	DIV %RBX
	# NOW THERE'S A VALUE ON %RAX
	ADD $0x30, %DL
	DEC %RCX
	MOV %DL, (%RCX)

	CMP $0, %RAX
	JNE CONV_LOOP

#	PRINT NUMB
	MOV $1, %RAX
	MOV $1, %RDI
	MOV %RCX, %RSI
	MOV %RSP, %RDX
	SUB %RCX, %RDX
	SYSCALL

#	PRINT '\n'
	MOV $10, %AL
	MOV %AL, (%RSP)

	MOV $1, %RAX
	MOV $1, %RDI
	MOV %RSP, %RSI
	MOV $1, %RDX
	SYSCALL

	ADD $32, %RSP
	RET
