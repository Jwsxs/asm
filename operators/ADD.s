.GLOBL ADD
.TEXT

ADD:

.L0:
	TEST %RSI, %RSI # TESTO PRIMEIRO SE O TRANSPORTE É POSSÍVEL
	JZ .L2

	MOV %RDI, %RAX # FIRST-ARGUMENT

	# SOMA
	AND %RSI, %RAX # CALCULA TRANSPORTE

	XOR %RSI, %RDI # CALCULA SOMA DOS BITS SEM TRANSPORTE

	SHL $1, %RAX # DESLOCA TUDO PRA ESQUERDA

	MOV %RAX, %RSI
	JMP .L0

.L2:
	MOV %RDI, %RAX
	RET
